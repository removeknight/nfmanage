const { readingPage } = require('../../utils/reading')
// logs.js
const util = require('../../utils/util.js')

readingPage({
  data: {
    logs: []
  },
  onLoad() {
    this.setData({
      logs: (wx.getStorageSync('logs') || []).map(log => {
        return {
          date: util.formatTime(new Date(log)),
          timeStamp: log
        }
      })
    })
  }
})
